// Creates the timer used to callback the LLMJVM_schedule() function.
// After its creation, the timer is idle.
/* cppcheck-suppress misra-c2012-5.5 ; intern/LLMJVM_impl.h, generated by the architecture, defines this name as a macro
 * that expands to itself. */
int32_t LLMJVM_IMPL_vmTaskStarted(void) {
	int32_t res = LLMJVM_ERROR;

	int32_t result = posix_timer_initialize();
	if (0 == result) {
		result = LLMJVM_IMPL_initialize_synchronization();
	}
	if (0 == result) {
		posix_timer_settimerexpiredhandler(&LLMJVM_IMPL_timer_expired);
		result = LLMJVM_IMPL_start_timer_thread();
	}
	if (0 == result) {
		res = LLMJVM_OK;
	}

	return res;
}

// Schedules requests from the VM
int32_t LLMJVM_IMPL_scheduleRequest(int64_t absolute_time) {
	posix_timer_schedule_timer(absolute_time);
	return LLMJVM_OK;
}

// Suspends the VM task if the pending flag is not set
/* cppcheck-suppress misra-c2012-5.5 ; intern/LLMJVM_impl.h, generated by the architecture, defines this name as a macro
 * that expands to itself. */
int32_t LLMJVM_IMPL_idleVM(void) {
	int32_t res = LLMJVM_ERROR;
	int32_t result = pthread_mutex_lock(&mutex);
	if (0 != result) {
		VEEPORT_LOGGER_LOG_ERR("cannot lock the Core Engine mutex (%s)", strerror(result));
	} else {
		res = LLMJVM_OK;
		if (!wokeup) {
			result = pthread_cond_wait(&condition, &mutex);
			if (0 != result) {
				VEEPORT_LOGGER_LOG_ERR("cannot wait for the Core Engine condition (%s)", strerror(result));
				res = LLMJVM_ERROR;
			}
		}
		result = pthread_mutex_unlock(&mutex);
		if (0 != result) {
			VEEPORT_LOGGER_LOG_ERR("cannot unlock the Core Engine mutex (%s)", strerror(result));
			res = LLMJVM_ERROR;
		}
	}
	return res;
}

// Wakes up the VM task and reset next wake up time
/* cppcheck-suppress misra-c2012-5.5 ; intern/LLMJVM_impl.h, generated by the architecture, defines this name as a macro
 * that expands to itself. */
int32_t LLMJVM_IMPL_wakeupVM(void) {
	int32_t res = LLMJVM_ERROR;
	int32_t result = pthread_mutex_lock(&mutex);
	if (0 != result) {
		VEEPORT_LOGGER_LOG_ERR("cannot lock the Core Engine mutex (%s)", strerror(result));
	} else {
		res = LLMJVM_OK;
		wokeup = MICROEJ_TRUE;
		result = pthread_cond_signal(&condition);
		if (0 != result) {
			VEEPORT_LOGGER_LOG_ERR("cannot signal the Core Engine condition (%s)", strerror(result));
			res = LLMJVM_ERROR;
		}
		result = pthread_mutex_unlock(&mutex);
		if (0 != result) {
			VEEPORT_LOGGER_LOG_ERR("cannot unlock the Core Engine mutex (%s)", strerror(result));
			res = LLMJVM_ERROR;
		}
	}
	return res;
}

// Clear the pending wake up flag
/* cppcheck-suppress misra-c2012-5.5 ; intern/LLMJVM_impl.h, generated by the architecture, defines this name as a macro
 * that expands to itself. */
int32_t LLMJVM_IMPL_ackWakeup(void) {
	int32_t res = LLMJVM_ERROR;
	int32_t result = pthread_mutex_lock(&mutex);
	if (0 != result) {
		VEEPORT_LOGGER_LOG_ERR("cannot lock the Core Engine mutex (%s)", strerror(result));
	} else {
		res = LLMJVM_OK;
		wokeup = MICROEJ_FALSE;
		posix_timer_reset();
		result = pthread_mutex_unlock(&mutex);
		if (0 != result) {
			VEEPORT_LOGGER_LOG_ERR("cannot unlock the Core Engine mutex (%s)", strerror(result));
			res = LLMJVM_ERROR;
		}
	}
	return res;
}

