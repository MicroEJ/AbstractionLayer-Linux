/* cppcheck-suppress misra-c2012-5.5 ; intern/LLMJVM_impl.h, generated by the architecture, defines this name as a macro
 * that expands to itself. */
int32_t LLMJVM_IMPL_shutdown(void) {
	int32_t res = LLMJVM_OK;

	posix_timer_stop();
	int32_t result = pthread_join(thread_ref, NULL);
	if (0 != result) {
		VEEPORT_LOGGER_LOG_ERR("cannot join the timer thread (%s)", strerror(result));
		res = LLMJVM_ERROR;
	}
	posix_timer_dispose();

	result = pthread_mutex_destroy(&mutex);
	if (0 != result) {
		VEEPORT_LOGGER_LOG_ERR("cannot destroy the Core Engine mutex (%s)", strerror(result));
		res = LLMJVM_ERROR;
	}
	result = pthread_cond_destroy(&condition);
	if (0 != result) {
		VEEPORT_LOGGER_LOG_ERR("cannot destroy the Core Engine condition (%s)", strerror(result));
		res = LLMJVM_ERROR;
	}
	return res;
}

