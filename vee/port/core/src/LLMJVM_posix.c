void LLMJVM_IMPL_setApplicationTime(int64_t t) {
	int32_t error_code = posix_time_setapplicationtime(t);

	if (0 != error_code) {
		/* This function returns void, so raising is the only way to tell the Application that the time it set was
		 * not applied. Reporting nothing is worse than failing: ej.bon.Util.setCurrentTimeMillis() would return
		 * normally and every later date the Application reads would be the one it believed it had replaced.
		 *
		 * RUNTIME_EXCEPTION_UNDEFINED because none of the declared codes describes a clock this process is not
		 * allowed to write, and it is the one code veeport_errors.h allows a message alongside. */
		VEEPORT_ERRORS_throw_runtime_exception_message(RUNTIME_EXCEPTION_UNDEFINED,
		                                               "cannot set the application time: %s", strerror(error_code));
	}
}

